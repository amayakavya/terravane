export const I18n = {
    current: () => localStorage.getItem('cc_lang') || 'en',
    set: (lang) => { localStorage.setItem('cc_lang', lang); I18n.apply(); },
    toggle: () => I18n.set(I18n.current() === 'en' ? 'hi' : 'en'),
    t: (key, vars) => {
        const lang = I18n.current();
        let str = (I18N[lang] && I18N[lang][key]) || I18N.en[key] || key;
        if (vars) Object.keys(vars).forEach(k => { str = str.replace('{' + k + '}', vars[k]); });
        return str;
    },
    apply: () => {
        const lang = I18n.current();
        document.documentElement.setAttribute('lang', lang === 'hi' ? 'hi' : 'en');
        document.body.setAttribute('data-lang', lang);
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            const vars = el.getAttribute('data-i18n-vars');
            el.textContent = I18n.t(key, vars ? JSON.parse(vars) : null);
        });
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            el.setAttribute('placeholder', I18n.t(el.getAttribute('data-i18n-placeholder')));
        });
        document.querySelectorAll('[data-lang-label]').forEach(el => {
            el.textContent = I18n.t('lang.toggle');
        });
    }
};
